    <p>Az idei év, így a pályázat és a tábor témája is a táj és az ember kapcsolata a környezet alakítása által. Azokat a beavatkozásokat, emberkéz alkotta szerkezeteket vesszük górcső alá, amelyek a táj szemlélésével foglalkoznak, vagyis az épített és természeti környezet közötti viszonyt feszegetik.</p>

