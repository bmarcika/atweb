    <p>Kiíróhoz a pályázati kiírásban megjelölt határidőig (2024.03.20.) az alábbi kérdések érkeztek. A válaszokat Kiíró a honlapján teszi közzé. A kérdés-válaszok a pályázati kiírás részeként kezelendők.</p>

    <p><b>1. Lehetőség van olyan építmény készítésére, ami esetleg betonból, kőből vagy vályogból épül és ezáltal ott marad a helyszínen?</b><br>Igen. Kiíró megjegyzi, hogy a pályázat gondolatisága fontos számára, így nem feltétlenül a megvalósíthatóság szempontja a döntő. Lásd kiírás 2. pont: “A pályázat fő célja pedig az építészeti tábor szellemi előkészítése”. Természetesen a megvalósíthatóság az értékelési szempontok közt szerepel, de nem az első helyen. </p>

    <p><b>2. Az objektum előállítási (anyag költségét) állja a fesztivál? 
    Ha igen, milyen költség határral?</b><br>A nyári alkotótábornak van meghatározott költségkerete, azonban az ott készülő objekt(ek) (makettek, vagy 1:1 léptékű építmények) nem feltétlenül a pályázati tervek közül fog(nak) kikerülni. Jelen pályázatnak nem célja a nyári alkotások megtervezése. Az alkotótábor önálló metodikával fog dolgozni a pályázattal megegyező tematikán, ezért a pályázat során nem feltétlenül kell foglalkozni a költségkerettel. </p>

    <p><b>3. Lehet olyan hasznalati tárgyat-epitmenyt tervezni amihez kiegészitő tárgyak tartoznak pl. kalyha Hot tub-hoz? </b><br>    
    Igen, tervezői döntés kérdése az 1. és 2. válaszok figyelembevételével. </p>


    <p><b>4. A kiírás 10. pontjának “kizárás körülményei” között szerepel, hogy “A pályázaton nem vehet részt, aki szakmai vagy jogi kapcsolatban van a zsűritagokkal és/vagy a szervezőkkel.” Kérjük pontosítani, hogy milyen szakmai vagy jogi kapcsolat esete kizáró ok. A kérdés arra irányul, hogy ha például az egyik zsűri tag tanárom az egyetemen, akkor pályázhatok-e.</b><br>
    Kiíró szakmai kapcsolat alatt az elmúlt két évben zajló közös tervezési munkában való részvételt ért. Jogi kapcsolat alatt a zsűri tagokkal azonos cégben dolgozókat érti. Az egyetemi curriculum keretei közt létrejött tanár-diák viszonyt nem tekinti szakmai kapcsolatnak, így az nem kizáró ok. Kiíró megjegyzi, hogy  a pontos jogi/szakmai kapcsolat firtatásánál fontosabbnak tartja az etikai normák betartását, amely az első kritériumként szerepel a kiírásban a kizárás esetei közt: “Bármilyen kommunikáció a zsűri tagjaival a pályázattal kapcsolatban”.</p>


    <p><b>5. Egy Natura 2000 Nemzeti Park, mint tervezési helyszín nem probléma tervezéskor?</b><br>
    A pályázati kiírás nem építési szándék alapján fogalmazódott meg, így a helyszín megválasztásakor a Nemzeti Parkkal Kiíró nem egyeztetett. Természetesen a nyári alkotótábor előtt Kiíró egyeztet a Nemzeti Parkkal amennyiben a tábor során ott bármilyen beavatkozás várható lesz. Kiíró fenntartja, hogy a pályázati feladat nem egy megvalósítható építmény tervezésére, hanem a felvetett téma gondolati gazdagságának kibontására irányul (lásd 1. válasz).</p>


    <p><b>6. Van lehetőség másik helyszín választására?</b><br>
    Nincs. A pályázat keretében a megadott helyszínre várunk koncepciókat; ez a pályamunkák összehasonlíthatósága miatt fontos.</p>


    <p><b>7. A kiírás szerint a tervet analóg technikákkal kell készíteni: kézi rajz és fizikai makett elfogadott. Makettfotó mellett más fotó elhelyezhető a tablón? Ebben az esetben digitális fénykép megengedett?</b><br>
    Igen, saját készítésű fényképet, vagy nem saját fénykép esetén manipulált (kollázs, montázs) fényképet el lehet helyezni a tablón. Természetesen fénykép esetén lehet digitális képet használni, utómunka, képszerkesztés megengedett.</p>


    <p><b>8. Az A2 méretű tablót is analóg technikával kell elkészíteni, vagy megengedett az, hogy számítógépes programmal készüljön? (pl. a rajzok kézzel készülnek, de azok külön beszkennelve digitálisan, pl. Photosoppal kerülnek elrendezésre a lapon). A feliratok gépelve készülhetnek, vagy kötelező kézírással feliratozni?</b><br>
    A tabló összeállítása megengedett számítógépes programmal. Digitális felirat elhelyezhető a tablón.</p>


    <p><b>9. Van lehetőség több pályázónak közös pályamű benyújtására?</b><br>
    Nincs, a pályázaton csak egyéni pályamunka nyújtható be. </p>


    <p><b>10. Amennyiben a pályázaton helyezést érek el, de nem tudok menni a táborba, a részvételi kedvezményt kiválthatom más formában, költségtérítésként, esetleg más programon való kedvezményes részvételi lehetőséggel?</b><br>
    Pénzjutalom csak az első helyezettet illeti, további helyezés esetén kedvezményes részvételt tudunk biztosítani. Amennyiben nyertes pályázó a Kővágóórs Alkotótábor másik nyári programján kíván résztvenni, a kedvezmény ott is érvényesíthető. Ebben az esetben eredményhirdetés után kiíróval egyeztetni szükséges a lehetőségekről, szabad helyekről. Az idei pályázat eredménye alapján azonban kizárólag idei programra vonatkozik a kedvezmény, jövő évre nem átvihető.</p>


    <p><b>11. Mi történik, ha két pályázó azonos kóddal adja be a pályázatot?</b><br>
    A beérkezett emaileket a titkárság kezeli, a zsűri csak a tablókat látja az értékeléskor. Ezt követően a titkárság azonosítja a pályamunkákat. A kód a könnyebb azonosíthatóságot szolgálja, de azonos kód esetén a titkárság ellenőrzi a pályázó személyét az email alapján.</p>


    <p><b>12. Megengedett-e a pályázatot társszerzővel készíteni, van-e lehetőség közös munkára a hallgatók között?</b><br>
    Lásd 9. választ.</p>


    <p><b>13. A végső tervet analóg technikával kell készíteni, de a makett készítése során lehet-e olyan eszközöket használni, mint 3D nyomtató, vagy lézervágó?</b><br>
    Igen. Lásd még: 7. és 8. választ.</p>


    <p><b>14. A tabló készítésében analóg technikának számít-e a kollázsolás, vagy nyomtatott anyagok felhasználása (például képekre rajzolás)?</b><br>
    Igen, ezek megengedettek, lásd még 7. és 8. választ.</p>


    <p><b>15. A helyszíni méréseket nekünk kell elvégezni? Amennyiben nem, mekkora a terület? Mik a szintmagasságok? Lehet-e kótázott helyszínrajzot kérni?</b><br>
    A területről nem áll rendelkezésre geodéziai felmérés sem helyszínrajz; Kiíró szerint az építészeti koncepció megalkotásához elegendő a megadott linken látható kép. Amennyiben Pályázó szükségesnek ítéli, a terület szabadon meglátogatható. Felmérést Kiíró nem vár el a Pályázóktól, a helyszínen lévő terepalakulatok nagyságrendi becsléssel közelíthetők. </p>


    <p><b>16. A terület beépítésével és a végső építészeti beavatkozás méretével kapcsolatban van-e valamilyen elvárás?</b><br>
    Nincs, a beavatkozás léptéke, mérete tervezési feladat és értékelési szempont is.</p>


    <p><b>17. A pályázat beadásához építésznek / építész hallgatónak kell lenni, vagy más szakterület (hallgatói) is pályázhatnak? </b><br>    
    Nincs megkötés, bármely szakterület képviselője, hallgatója nyújthat be pályázatot. </p>

          
    
