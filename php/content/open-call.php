    <h3 class="at-subt at-fontweight-900 at-text-lowercase">eredményhirdetés</h3>
    
    <p>A Bíráló Bizottság egybehangzó véleménye szerint a beérkezett pályaművek  gondolatiságukban és grafikai kivitelezésükben egyaránt magas színvonalon készültek. Az összes pályamű megfelelt az analóg technikák használatával kapcsolatos követelménynek, ezért a tablók változatos, egyéni megjelenésűek. A felhasznált technikák között találhatunk többek közt kézi rajzot, akvarellt,  kollázst, makettfotót, fényképeket.</p>

    <p>Elméleti megközelítésben a pályaművek mindegyike igen személyes hangvételű volt, a tájjal való kapcsolatot saját érzésein és benyomásain keresztül próbálta megfejteni és a terven keresztül egy elképzelt tágabb közönség számára is elérhetővé tenni. </p>

